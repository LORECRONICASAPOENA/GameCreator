"use strict";
const assert=require("node:assert/strict");
const {Hidrologia,fromMap,SCHEMA}=require("../../map-editor/hidrologia-core.js");
const h=new Hidrologia(16,16);
assert.equal(h.size,256);
assert.equal(h.get(0,0).elevation,0);
for(let level=1;level<=6;level++){
 const b=new Hidrologia(16,16);
 b.paintBasin(8,8,3,level);
 assert.equal(b.get(8,8).capacity,level);
 assert.ok(b.get(8,8).elevation<=-level);
}
const rain=new Hidrologia(16,16);
rain.paintElevation(4,4,1,3);
rain.paintBasin(7,7,3,4);
const before=rain.water.reduce((sum,v)=>sum+v,0);
for(let t=0;t<15;t++)rain.advance({rain:.19,sun:0});
const after=rain.water.reduce((sum,v)=>sum+v,0);
assert.ok(after>before,"Chuva aumenta a agua");
assert.ok(rain.water.some(v=>v>.08),"Chuva deixa celulas molhadas");
const save=rain.serialize();
assert.equal(save.schema,SCHEMA);
const loaded=Hidrologia.fromData(save);
assert.deepEqual(loaded.water,rain.water);
assert.deepEqual(loaded.elevation,rain.elevation);
const map={schema:"apoena.map2d.v1",width:16,height:16,heights:Array(256).fill(1)};
assert.equal(fromMap(map).get(0,0).elevation,1);
map.hydrology=save;
assert.equal(fromMap(map).get(8,8).capacity,4);
let protectedSoil=new Hidrologia(10,10);
protectedSoil.paintElevation(5,5,1,3);
protectedSoil.setSoil(5,5,{protected:1,hardness:0});
const first=protectedSoil.get(5,5).elevation;
for(let i=0;i<20;i++)protectedSoil.advance({rain:.3,sun:0});
assert.equal(protectedSoil.get(5,5).elevation,first,"Terreno protegido nao erode");
let drought=new Hidrologia(8,8);
drought.water[0]=2;
const old=drought.water[0];
drought.advance({rain:0,sun:.3});
assert.ok(drought.water[0]<old,"Sol seca a agua");
assert.throws(()=>Hidrologia.fromData({schema:SCHEMA,width:8,height:8,elevation:[]}));
console.log("HIDROLOGIA OK: seis niveis, chuva, secagem, protecao, importacao e salvamento.");
